from typing import List, Optional, Literal, Dict, Any
from pydantic import BaseModel, Field, field_validator


class ChatMessage(BaseModel):
    """Individual message in a chat conversation."""
    role: Literal["system", "user", "assistant", "function", "tool"] = Field(
        ..., description="Role of the message author"
    )
    content: str = Field(..., description="Contents of the message")
    name: Optional[str] = Field(None, description="Optional name for the author")

    @field_validator("content")
    @classmethod
    def validate_content_not_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Message content cannot be empty or whitespace only")
        return v


class ChatCompletionRequest(BaseModel):
    """OpenAI-compatible chat completion request schema."""
    model: str = Field(
        default="champion-gpt-4o",
        description="ID of the model to use for completion"
    )
    messages: List[ChatMessage] = Field(
        ...,
        min_length=1,
        description="A list of messages comprising the conversation so far"
    )
    temperature: Optional[float] = Field(
        default=0.7,
        ge=0.0,
        le=2.0,
        description="Sampling temperature between 0.0 and 2.0"
    )
    top_p: Optional[float] = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Nucleus sampling probability threshold"
    )
    max_tokens: Optional[int] = Field(
        default=None,
        gt=0,
        description="Maximum number of tokens to generate in the completion"
    )
    stream: bool = Field(
        default=False,
        description="Whether to stream partial message deltas (disabled for verified shadowing)"
    )
    metadata: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional custom metadata attached to the request for tracing"
    )


class ChatCompletionChoice(BaseModel):
    """Single completion choice in the response."""
    index: int = 0
    message: ChatMessage
    finish_reason: Literal["stop", "length", "tool_calls", "content_filter"] = "stop"


class CompletionUsage(BaseModel):
    """Token usage breakdown for the request."""
    prompt_tokens: int = Field(..., description="Tokens consumed by the prompt")
    completion_tokens: int = Field(..., description="Tokens generated by the model")
    total_tokens: int = Field(..., description="Total tokens consumed")


class ChatCompletionResponse(BaseModel):
    """OpenAI-compatible chat completion response schema."""
    id: str = Field(..., description="Unique completion ID")
    object: Literal["chat.completion"] = "chat.completion"
    created: int = Field(..., description="Unix timestamp in seconds of response generation")
    model: str = Field(..., description="Model identifier used for generation")
    choices: List[ChatCompletionChoice] = Field(..., description="List of completion choices")
    usage: CompletionUsage = Field(..., description="Token usage details")
    system_fingerprint: Optional[str] = Field(
        default="fp_crossverify_champion",
        description="Unique system fingerprint"
    )
